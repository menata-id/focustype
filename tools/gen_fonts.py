#!/usr/bin/env python3
"""Renders IBM Plex into 1-bit bitmap fonts for the firmware.

Reads the TTFs in third_party/ibm-plex and writes
  components/gfx/fonts_generated.c
  components/gfx/include/gfx_fonts.h

Run: python3 -I tools/gen_fonts.py        (needs Pillow)
"""
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
TTF = ROOT / "third_party" / "ibm-plex"
OUT_C = ROOT / "components" / "gfx" / "fonts_generated.c"
OUT_H = ROOT / "components" / "gfx" / "include" / "gfx_fonts.h"

# name, ttf, pixel size. Sizes follow the mockup.
FONTS = [
    ("plex_mono_17", "IBMPlexMono-Regular.ttf", 17),   # editor body
    ("plex_mono_17_medium", "IBMPlexMono-Medium.ttf", 17),
    ("plex_mono_15", "IBMPlexMono-Regular.ttf", 15),   # rename field
    ("plex_sans_12", "IBMPlexSans-Regular.ttf", 12),   # hints, metadata
    ("plex_sans_12_semibold", "IBMPlexSans-SemiBold.ttf", 12),  # key caps
    ("plex_sans_13", "IBMPlexSans-Regular.ttf", 13),
    ("plex_sans_13_bold", "IBMPlexSans-Bold.ttf", 13),  # header bar
    ("plex_sans_15_semibold", "IBMPlexSans-SemiBold.ttf", 15),
    ("plex_sans_15_bold", "IBMPlexSans-Bold.ttf", 15),
    ("plex_sans_16_semibold", "IBMPlexSans-SemiBold.ttf", 16),
    ("plex_sans_17_bold", "IBMPlexSans-Bold.ttf", 17),
    ("plex_sans_18_bold", "IBMPlexSans-Bold.ttf", 18),
    ("plex_sans_19_bold", "IBMPlexSans-Bold.ttf", 19),
]

# ASCII plus the punctuation and arrows the mockup text uses. Glyphs a font lacks are skipped
# (and reported); the UI draws ▸ ● ✕ ⚑ as shapes instead.
CODEPOINTS = list(range(0x20, 0x7F)) + [
    0x00B7,  # ·
    0x2014,  # —
    0x2018, 0x2019, 0x201C, 0x201D,  # ‘ ’ “ ”
    0x2026,  # …
    0x2190, 0x2191, 0x2192, 0x2193,  # ← ↑ → ↓
]


def render_glyph(font, ascent, descent, size, cp):
    ch = chr(cp)
    adv = round(font.getlength(ch))
    margin = size
    w = adv + 2 * margin
    h = ascent + descent + 2 * margin
    im = Image.new("1", (w, h), 0)
    d = ImageDraw.Draw(im)
    d.fontmode = "1"  # no anti-aliasing
    d.text((margin, margin + ascent), ch, font=font, fill=1, anchor="ls")
    bbox = im.getbbox()
    if bbox is None:
        return dict(cp=cp, adv=adv, w=0, h=0, xoff=0, yoff=0, rows=[], blank=True)
    x0, y0, x1, y1 = bbox
    rows = []
    for y in range(y0, y1):
        rows.append([1 if im.getpixel((x, y)) else 0 for x in range(x0, x1)])
    return dict(cp=cp, adv=adv, w=x1 - x0, h=y1 - y0,
                xoff=x0 - margin, yoff=y0 - (margin + ascent), rows=rows, blank=False)


def pack(rows, w):
    stride = (w + 7) // 8
    out = []
    for r in rows:
        for bx in range(stride):
            b = 0
            for k in range(8):
                x = bx * 8 + k
                if x < w and r[x]:
                    b |= 0x80 >> k
            out.append(b)
    return out


def build_font(name, ttf, size):
    font = ImageFont.truetype(str(TTF / ttf), size)
    ascent, descent = font.getmetrics()
    # A codepoint the font does not map renders its .notdef box; use that to detect gaps.
    notdef = render_glyph(font, ascent, descent, size, 0xE000)["rows"]
    glyphs, bitmap, missing = [], [], []
    for cp in CODEPOINTS:
        g = render_glyph(font, ascent, descent, size, cp)
        if cp > 0x20 and not g["blank"] and g["rows"] == notdef:
            missing.append(cp)
            continue
        packed = pack(g["rows"], g["w"])
        g["off"] = len(bitmap)
        bitmap.extend(packed)
        glyphs.append(g)
    return dict(name=name, ascent=ascent, line_h=ascent + descent, glyphs=glyphs,
                bitmap=bitmap, missing=missing)


def emit(fonts):
    c = ["/* Generated by tools/gen_fonts.py. Do not edit.",
         " *",
         " * Bitmaps rendered from IBM Plex (Copyright (c) 2017 IBM Corp. with Reserved Font Name",
         " * \"Plex\"), licensed under the SIL Open Font License 1.1. See third_party/ibm-plex/OFL.txt.",
         " */",
         "", '#include "gfx_fonts.h"', ""]
    h = ["#pragma once", "", '#include "gfx_text.h"', "",
         "/* Generated by tools/gen_fonts.py. */", ""]
    for f in fonts:
        n = f["name"]
        c.append(f"static const uint8_t {n}_bits[] = {{")
        bm = f["bitmap"]
        for i in range(0, len(bm), 16):
            c.append("    " + ", ".join(f"0x{b:02X}" for b in bm[i:i + 16]) + ",")
        c.append("};")
        c.append(f"static const gfx_glyph_t {n}_glyphs[] = {{")
        for g in f["glyphs"]:
            c.append(f"    {{0x{g['cp']:04X}, {g.get('off', 0)}, {g['w']}, {g['h']}, "
                     f"{g['xoff']}, {g['yoff']}, {g['adv']}}},")
        c.append("};")
        c.append(f"const gfx_font_t font_{n} = {{{n}_glyphs, {len(f['glyphs'])}, {n}_bits, "
                 f"{f['ascent']}, {f['line_h']}}};")
        c.append("")
        h.append(f"extern const gfx_font_t font_{n};")
    OUT_C.write_text("\n".join(c) + "\n")
    OUT_H.write_text("\n".join(h) + "\n")


def main():
    fonts = [build_font(*spec) for spec in FONTS]
    for f in fonts:
        extra = ""
        if f["missing"]:
            extra = "  missing: " + " ".join(f"U+{c:04X}" for c in f["missing"])
        print(f"{f['name']:24s} {len(f['glyphs']):3d} glyphs  {len(f['bitmap']):5d} B  "
              f"line {f['line_h']}px{extra}")
    emit(fonts)
    total = sum(len(f["bitmap"]) for f in fonts)
    print(f"total bitmap data: {total} bytes")


if __name__ == "__main__":
    sys.exit(main())
